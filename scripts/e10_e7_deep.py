#!/usr/bin/env python3
"""E10: deep baselines under the e7 natural-missingness protocols (IoTJ-R1, R1-1).

Why: Table A/B (natural pattern + synchronized group failure) cover DMHI +
Linear/LOCF/Mean only; the material honestly flagged deep baselines as not
rerun. This script reruns the four learning baselines (ImputeFormer, SAITS,
TimeMixer, CSDI) on the two e7 datasets under the SAME six protocols.

Setting (deployment-robustness, matches DMHI's E2-checkpoint reuse in e7):
each baseline is TRAINED ONCE per (dataset, seed) with the paper protocol
(block20, rho=0.9) — the identical training recipe as Table II — then the
fitted model is re-imputed under each of the six e7 test masks via the
runners' extra_test_masks hook. Masks are generated by e7's own generators
(native_pattern_mask / group_outage_mask) with the same seeds, so hide sets
are bit-identical to Table A/B's.

Outputs: runs/e10_e7_deep/e10_<ds>_seed<s>_<method>.json per training run
(the runner's results dict incl. extra_masks), plus per-protocol imputed
npy files (naming handled by the runners).

Usage (server, riemann_baselines env, repo root):
    python scripts/e10_e7_deep.py --gpu 1
    python scripts/e10_e7_deep.py --gpu 1 --methods imputeformer --datasets air_quality_italy --seeds 7
"""
import argparse
import json
import pathlib
import sys

import numpy as np

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "baselines"))

from e7_natural_missing import native_pattern_mask, group_outage_mask  # noqa: E402

DATASETS = ["air_quality_italy", "physionet2012"]
SEEDS = [7, 42, 123]
OUT_DIR = pathlib.Path("runs/e10_e7_deep")


def build_hides(M_test, seed, M_test_full=None):
    """Replicates e7's protocol construction bit-for-bit: native mask at
    seed, group masks at seed + 17*n_ch + run_len (see e7_natural_missing
    main()). M_full defaults to M_test (the loader returns the natural mask)."""
    hides = {}
    M_full = M_test_full if M_test_full is not None else M_test
    hides["native_pattern"] = native_pattern_mask(M_full, M_full, seed=seed)
    for n_ch, run_len in [(2, 12), (4, 12), (8, 12), (2, 24), (4, 24)]:
        hides[f"group{n_ch}x{run_len}"] = group_outage_mask(
            M_full, n_ch, run_len, seed=seed + 17 * n_ch + run_len)
    return hides


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gpu", type=int, default=0)
    ap.add_argument("--datasets", nargs="*", default=DATASETS)
    ap.add_argument("--seeds", nargs="*", type=int, default=SEEDS)
    ap.add_argument("--methods", nargs="*",
                    default=["imputeformer", "saits", "timemixer", "csdi"])
    args = ap.parse_args()

    from common import load_dataset

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    for ds in args.datasets:
        _, _, _ = load_dataset(ds, "train")
        _, M_test, _ = load_dataset(ds, "test")
        # e7 reads data/processed/<ds>/M_test.npy directly; the loader's test
        # mask is the same array — assert equality to be safe.
        import numpy as _np
        M_raw = _np.load(f"data/processed/{ds}/M_test.npy").astype(np.int8)
        assert (M_raw == M_test).all(), f"M_test mismatch for {ds}"
        for seed in args.seeds:
            hides = build_hides(M_test, seed)
            for method in args.methods:
                out_path = OUT_DIR / f"e10_{ds}_seed{seed}_{method}.json"
                if out_path.exists():
                    print(f"[e10] skip {ds} seed{seed} {method}")
                    continue
                if method == "imputeformer":
                    from run_imputeformer import run_one
                    res = run_one(ds, 0.9, "block20", args.gpu,
                                  str(OUT_DIR / f"_work_{ds}_seed{seed}"),
                                  seed=seed, extra_test_masks=hides)
                elif method == "saits":
                    from run_saits import run_one
                    res = run_one("saits", ds, 0.9, "block20", args.gpu,
                                  str(OUT_DIR / f"_work_{ds}_seed{seed}"),
                                  seed=seed, extra_test_masks=hides)
                elif method == "timemixer":
                    from run_timemixer import run_one
                    res = run_one(ds, 0.9, "block20", args.gpu,
                                  str(OUT_DIR / f"_work_{ds}_seed{seed}"),
                                  seed=seed, extra_test_masks=hides)
                elif method == "csdi":
                    from run_csdi import run_one
                    res = run_one(ds, 0.9, "block20", args.gpu,
                                  str(OUT_DIR / f"_work_{ds}_seed{seed}"),
                                  seed=seed, extra_test_masks=hides)
                else:
                    raise ValueError(method)
                with open(out_path, "w") as f:
                    json.dump(res, f, indent=1, default=float)
                extra = res.get("extra_masks", {})
                em = {k: v.get("mae") for k, v in extra.items()}
                print(f"[e10] {ds} seed{seed} {method} extra MAE: {em}")


if __name__ == "__main__":
    main()
